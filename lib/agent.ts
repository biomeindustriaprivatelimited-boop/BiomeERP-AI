/**
 * Rule-based automation "agent" for the Biome Industria platform.
 *
 * This is intentionally NOT a call to any external AI API. Everything here
 * runs synchronously in the browser using plain keyword matching and date
 * math, so it works fully offline and has zero ongoing cost.
 */

export interface AgentRoute {
  href: string;
  label: string;
}

export interface AgentReply {
  text: string;
  route?: AgentRoute;
}

interface Rule {
  id: string;
  keywords: string[];
  reply: (query: string) => AgentReply;
}

