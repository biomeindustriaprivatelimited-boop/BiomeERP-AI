export function dueDateSummary(now: Date = new Date()): string {
  const day = now.getDate();
  const monthName = now.toLocaleDateString("en-IN", { month: "long" });
  const lines = [
    `GSTR-1: 11th of every month${day <= 11 ? " (upcoming this month)" : " (passed for " + monthName + ")"}`,
    `GSTR-3B: 20th of every month${day <= 20 ? " (upcoming this month)" : " (passed for " + monthName + ")"}`,
    "GSTR-2B: auto-generated by the portal, usually by the 14th — no separate filing",
  ];
  return `Standard monthly due dates:\n${lines.join("\n")}\n(Always confirm against the latest CBIC notification for your filing frequency.)`;
}

/** Same keyword matching as matchIntent, but returns null instead of a
 *  canned "I didn't recognise that" reply when nothing matches — lets a
 *  caller fall through to the local AI model for open-ended questions
 *  while still using instant, zero-cost rule matching for common app
 *  navigation commands. */
export function tryMatchIntent(query: string): AgentReply | null {
  const q = query.toLowerCase().trim();
  if (!q) return null;
  for (const rule of RULES) {
    if (rule.keywords.some((kw) => q.includes(kw))) {
      return rule.reply(q);
    }
  }
  return null;
}

export function matchIntent(query: string): AgentReply {
  const q = query.toLowerCase().trim();
  if (!q) {
    return { text: "Ask me about reconciliation, GST filing, OCR scanning, or WhatsApp documents." };
  }
  for (const rule of RULES) {
    if (rule.keywords.some((kw) => q.includes(kw))) {
      return rule.reply(q);
    }
  }
  return {
    text: "I didn't recognise that — I only understand a fixed set of app commands (I'm rule-based, not a language model). Try \"help\" to see what I can do.",
  };
}
