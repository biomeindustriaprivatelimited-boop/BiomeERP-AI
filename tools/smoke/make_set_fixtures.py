def pdf(name, pages):
    c = canvas.Canvas(os.path.join(HERE, name), pagesize=A4)
    c.setTitle("synthetic smoke fixture")
    for lines in pages:
        y = 810
        c.setFont("Courier", 8)
        for line in lines:
            c.drawString(28, y, line)
            y -= 11
        c.showPage()
    c.save()


