def screenshot(name):
    img = Image.new("RGB", (540, 960), (236, 229, 221))
    d = ImageDraw.Draw(img)
    try:
        f = ImageFont.truetype("DejaVuSans.ttf", 26)
    except Exception:
        f = ImageFont.load_default()
    d.rectangle([0, 0, 540, 90], fill=(7, 94, 84))
    d.text((24, 30), "Rahul (driver)", fill=(255, 255, 255), font=f)
    bubbles = ["Good morning sir", "Reached the gate", "ok", "Thank you"]
    y = 140
    for i, b in enumerate(bubbles):
        x = 40 if i % 2 == 0 else 220
        d.rounded_rectangle([x, y, x + 280, y + 70], 16, fill=(255, 255, 255) if i % 2 == 0 else (220, 248, 198))
        d.text((x + 18, y + 20), b, fill=(20, 20, 20), font=f)
        y += 120
    img.save(os.path.join(HERE, name), "JPEG", quality=80)


