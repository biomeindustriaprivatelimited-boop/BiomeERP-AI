function readOurInvoiceOrChallan(text, ctx) {
  const t = String(text || "");
  const ourNo = ourDocNumber(t);
  if (!ourNo) return null;
  if (biomeIsBuyer(t)) return null;
  if (!/biome\s*industria/i.test(head(t, 1500))) return null;
  const upper = t.toUpperCase();
  let documentType = null;
  let layout = null;
  if (/\bDELIVERY\s*CHALLAN\b/.test(upper) && /\bBI\s?\/\s?[A-Z]+\s?\/[A-Z]+\s?\/\s?\d+/.test(upper)) {
    documentType = "biome_delivery_challan";
    layout = "biome_ntpc_delivery_challan";
  } else if (/\bDELIVERY\s*NOTE\b/.test(head(upper, 200)) || /DELIVERY\s*NOTE\s*NO/.test(upper) || /BIPL\s?\/\s?\d{4}-\d{2}/.test(upper)) {
    documentType = "biome_delivery_challan";
    layout = "biome_tally_delivery_note";
  } else if (/TAX\s*INVOICE/.test(upper) && /\bBI-?\s?\d{2}-?\s?\d{2}-?\s?[A-Z]{2}\s?\d{3,5}\b/.test(upper)) {
    documentType = "biome_tax_invoice";
    layout = "biome_tally_tax_invoice";
  } else {
    return null;
  }
  const out = {
    layout,
    documentType,
    issuerSide: "us",
    confidence: 98,
    biomeDocNo: ourNo,
    ourDocCore: docCore(ourNo),
    referenceNo: referenceIn(t),
  };
  out.documentDate =
    firstDateAfter(t, /(?:^|\n|\|)\s*Dated\b\s*:?/i, 40) ||
    firstDateAfter(t, /Challan\s*No\.?[^\n]{0,40}?Date\s*:?/i, 30) ||
    firstDateAfter(t, /Ack\s*Date\s*:?/i, 20) ||
    allDates(t)[0] ||
    null;
  // e-way number: printed in the header next to our number
  const ew = ewayNumbers(t).filter((n) => !/^1\d{11}$/.test(n) || true);
  const irnFree = ew.filter((n) => !new RegExp(`Ack\\s*No\\.?\\s*:?\\s*${n}`).test(t.replace(/\s/g, "")));
  out.ewayBillNo = firstMatch(t.replace(/(\d{4})\s(\d{4})\s(\d{4})/g, "$1$2$3"), /e-?\s?way\s*bill\s*No\.?\s*:?\s*\|?\s*(?:[A-Z0-9\/-]+\s+)?(\d{12})\b/i) || irnFree[0] || null;
  // LR / Bill T number: "Bill of Lading/LR-RR No. … 25 dt. 1-Aug-26"
  const lr = firstMatch(t, /(?:^|\n|\|)\s*(\d{1,6})\s*dt\.\s*\d{1,2}[-\s]/i) || firstMatch(t, /LR-?RR\s*No\.?\s*:?\s*\|?\s*(\d{1,6})\b/i);
  out.grNumber = lr || null;
  const vehicleAfterLabel = firstMatch(t, /(?:Motor\s*Vehicle\s*No\.?|Lorry\s*No\.?|Vehicle\s*No\.?)\s*:?\s*\|?\s*([A-Z]{2}\s?\d{1,2}\s?[A-Z]{0,3}\s?\d{4})/i);
  out.vehicleNo = vehicleAfterLabel ? vehicleAfterLabel.replace(/\s/g, "").toUpperCase() : platesIn(t)[0] || null;
  out.quantityKg = quantityKg(t);
  // client: consignee and buyer blocks
  out.consigneeName = firstLineAfter(t, /Consignee\s*\(\s*Ship\s*to\s*\)/i) || firstLineAfter(t, /Goods\s*Shipped\s*to\s*:?/i);
  out.buyerName = firstLineAfter(t, /Buyer\s*\(\s*Bill\s*to\s*\)/i) || firstLineAfter(t, /Billing\s*Address\s*:?/i);
  out.clientName = chooseClient([out.buyerName, out.consigneeName], ctx, t);
  const g = gstinsIn(t).map((x) => x.gstin).filter((x) => !isOurGstin(x));
  out.clientGstin = g[0] || null;
  out.plantCode = /\/(REW|GKD)\//.test(String(out.referenceNo || "")) ? out.referenceNo.split("/")[2] : null;
  return out;
}

function firstLineAfter(text, labelRe) {
  const m = String(text || "").match(labelRe);
  if (!m) return null;
  const rest = String(text).slice(m.index + m[0].length).split(/\n|\|/).map((s) => s.trim()).filter(Boolean);
  for (const line of rest.slice(0, 3)) {
    if (/^(M\/S\.?|:|-)$/i.test(line)) continue;
    const clean = line.replace(/^M\/S\.?\s*/i, "").trim();
    if (clean.length >= 3 && !/^(gstin|state|invoice|dated|buyer|delivery)/i.test(clean)) return clean.slice(0, 80);
  }
  return null;
}

/**
 * Which party is the client: the buyer when it is on the client list,
 * else the consignee when it is, else whichever names a known client in
 * the text. The owner's sales register lists the BUYER (Somani Biofuels
 * on BI-26-27-HR0808, shipped to NTPC Dadri); a delivery note billed to
 * a vendor (Terra Biofuel) but shipped to HTPS belongs to HTPS.
 */
function chooseClient(names, ctx, text, opts = {}) {
  const clients = (ctx && ctx.clients) || [];
  let matchClient = null;
  try { matchClient = require("./clients").matchClient; } catch { /* optional */ }
  if (matchClient && clients.length) {
    for (const n of names) {
      if (!n) continue;
      const c = matchClient(n, clients);
      if (c) return c.name;
    }
    // NTPC prints one GSTIN per state; the station name tells them apart.
    if (/\bNTPC\b/i.test(text || "")) {
      const place = String(text).match(/\b(solapur|mouda|tanda|vindhyachal|vindhyanchal|dadri|khargone|barh|kudgi|lara|sipat|korba)\b/i);
      if (place) {
        const c = matchClient(`NTPC ${place[1]}`, clients);
        if (c) return c.name;
      }
    }
  }
  if (opts.matchedOnly) return null;
  return names.find((n) => n && !/^(msme|gstin|state|p\.?o\.?|billing|goods)\b/i.test(n)) || null;
}

function readOurEwayOrVendorEway(text) {
  const t = String(text || "");
  if (!isEwayPage(t)) return null;
  const flat = t.replace(/­/g, "-");
  const genBy = firstMatch(flat, /Generated\s*By\s*:?\s*\|?\s*([0-9O]{2}\s?[A-Z0-9]{3,5}\s?[A-Z0-9]{3,5}\s?[A-Z0-9]{2,5}\s?[A-Z0-9]{0,3})/i);
  const supplier = firstMatch(flat, /GSTIN\s*of\s*Supplier\s*:?\s*\|?\s*([0-9O]{2}\s?[A-Z0-9 ]{11,16})/i);
  const fromG = gstinsIn(flat);
  let issuer = normGstin(genBy) || normGstin(supplier) || (fromG[0] && fromG[0].gstin) || null;
  // OCR can drop characters from "Generated By"; the "From" GSTIN is the next witness
  if (!issuer && fromG.length) issuer = fromG[0].gstin;
  const ours = issuer ? isOurGstin(issuer) : /generated\s*by\s*:?\s*\|?\s*[0O]6\s?AAJ\s?CB/i.test(flat);
  const nums = ewayNumbers(flat);
  const ewayBillNo =
    firstMatch(flat.replace(/(\d{4})\s(\d{4})\s(\d{4})/g, "$1$2$3"), /e-?\s?way\s*bil+\s*No\.?\s*:?\s*\|?\s*(\d{12})/i) || nums[0] || null;
  // the document it covers
  let docNo =
    firstMatch(flat, /Doc(?:ument)?\s*No\.?\s*:?\s*(?:Tax\s*Invoice|Delivery\s*Challan|Challan|Bill\s*of\s*Supply)\s*-\s*([A-Z0-9][A-Z0-9\/\-]*)/i) ||
    firstMatch(flat, /Document\s*Details\s*:?\s*(?:Tax\s*Invoice|Delivery\s*Challan|Challan|Others?)\s*-?\s*\|?\s*([A-Z0-9][A-Z0-9\/\-]*)/i) ||
    firstMatch(flat, /Document\s*No\.?\s*:?\s*\|?\s*([A-Z0-9][A-Z0-9\/\-]*)/i);
  if (docNo && /^(document|date|transaction|\d{2}\/\d{2}\/\d{4})$/i.test(docNo)) docNo = null;
  if (ours) {
    const own = ourDocNumber(flat);
    if (own) docNo = own;
  }
  const vehicleRow = firstMatch(flat, /\b(?:Road|ROAD)\s*[—-]?\s*([A-Z]{2}\s?\d{1,2}\s?[A-Z]{0,3}\s?\d{4})/);
  const vehicleLbl = firstMatch(flat, /Vehicle\s*No\.?\s*:?\s*([A-Z]{2}\s?\d{1,2}\s?[A-Z]{0,3}\s?\d{4})/i);
  const vehicle = (vehicleLbl || vehicleRow || "").replace(/\s/g, "").toUpperCase().replace(/^PBO/, "PB0") || platesIn(flat)[0] || null;
  const date =
    firstDateAfter(flat, /Document\s*Date\s*:?/i, 30) ||
    firstDateAfter(flat, /(?:Generated\s*Date|E-?Way\s*Bill\s*Date)\s*:?/i, 30) ||
    firstDateAfter(flat, /Doc\s*No\.?[^\n]*\n\s*Date\s*:?/i, 20) ||
    allDates(flat)[0] ||
    null;
  const transporter =
    firstMatch(flat, /Transporter\s*ID\s*&\s*Name\s*:\s*([A-Za-z][A-Za-z .&]{2,50}?)\s*(?:Transporter\s*Doc|\n|\|)/i) ||
    firstMatch(flat, /Transporter\s+[0-9O]{2}[A-Z0-9]{13}\s*&\s*([A-Za-z][A-Za-z .&]{2,50})/i);
  const transporterGstin = normGstin(firstMatch(flat, /Transporter\s*(?:ID\s*:?)?\s*([0-9O]{2}[A-Z0-9]{13})/i));
  const lr = firstMatch(flat, /Transporter\s*Doc\.?\s*No\.?\s*&?\s*Date\s*:\s*(\d{1,6})\s*&/i) || firstMatch(flat, /\b[A-Z]{2}\d{1,2}[A-Z]{0,3}\d{4}\s*&\s*(\d{1,6})\s*&/);
  const out = {
    layout: ours ? "biome_eway_bill" : "vendor_eway_bill",
    documentType: ours ? "biome_eway_bill" : "vendor_eway_bill",
    issuerSide: ours ? "us" : "them",
    confidence: issuer || genBy ? 97 : 90,
    ewayBillNo,
    ewayDocNo: docNo,
    documentDate: date,
    vehicleNo: vehicle,
    quantityKg: quantityKg(flat),
    transporterName: transporter ? transporter.trim() : null,
    transporterGstin: transporterGstin || null,
    grNumber: lr || null,
  };
  if (ours) {
    out.biomeDocNo = docNo;
    out.ourDocCore = docCore(docNo);
  } else {
    out.vendorGstin = issuer && !isOurGstin(issuer) ? issuer : null;
    out.vendorDocNo = docNo;
    out.vendorOwnDocNo = docNo;
    out.vendorDocCore = docCore(docNo);
    const vname = firstMatch(flat, /GSTIN\s*of\s*Supplier\s*[0-9O]{2}[A-Z0-9 ]{13,17}\s*,\s*([A-Z][A-Za-z .&]{2,50})/i) || firstMatch(flat, /Generated\s*By\s*:?\s*[0-9O]{2}[A-Z0-9 ]{13,17}\s*-\s*([A-Z][A-Za-z .&]{2,50})/i);
    if (vname) out.vendorName = vname.trim();
  }
  return out;
}

function readConsignmentTag(text, ctx) {
  const t = String(text || "");
  if (!isConsignmentTag(t)) return null;
  const batch = firstMatch(t, /Batch\s*(?:Number|No\.?)\s*:?\s*\|?\s*([A-Z0-9][A-Z0-9\/\-]{2,30})/i);
  const ourNo = ourDocNumber(batch || "") || null;
  const vehicle = platesIn(t)[0] || null;
  const mat = firstMatch(t, /Material\s*(?:weight|Weight)?\s*:?\s*\|?\s*([\d,]{4,7})\s*KG/i) || firstMatch(t, /([\d,]{4,7})\s*KG\b/i);
  const gross = firstMatch(t, /Gross\s*(?:weight|Weight)\s*:?\s*\|?\s*([\d,]{4,7})/i);
  const tare = firstMatch(t, /Tare\s*(?:weight|Weight)\s*:?\s*\|?\s*([\d,]{4,7})/i);
  const date = firstDateAfter(t, /Date\s*of\s*dispatch\s*:?\s*-?/i, 40) || allDates(t)[0] || null;
  return {
    layout: "consignment_tag",
    documentType: "consignment_tag",
    issuerSide: /biome\s*industria/i.test(t) ? "us" : "shared",
    confidence: 97,
    vehicleNo: vehicle,
    documentDate: date,
    netWeight: mat ? String(Number(mat.replace(/,/g, ""))) : null,
    quantityKg: mat ? Number(mat.replace(/,/g, "")) : null,
    grossWeight: gross ? String(Number(gross.replace(/,/g, ""))) : null,
    tareWeight: tare ? String(Number(tare.replace(/,/g, ""))) : null,
    biomeDocNo: ourNo,
    ourDocCore: ourNo ? docCore(ourNo) : null,
    batchNo: batch || null,
  };
}

function readVendorInvoice(text, ctx) {
  const t = String(text || "").replace(/­/g, "-");
  const upper = t.toUpperCase();
  const einvoiceDetail = /e-?\s?invoice\s*details/i.test(t) && /document\s*type\s*:?\s*tax\s*invoice/i.test(t);
  const titled = /T\s?A\s?X\s*I\s?N\s?V\s?O\s?[IL]\s?C\s?E/.test(upper) || einvoiceDetail;
  if (!titled) return null;
  if (ourDocNumber(t) && !biomeIsBuyer(t)) return null; // ours
  const gst = gstinsIn(t);
  const ourSeen = gst.some((g) => isOurGstin(g.gstin)) || /biome\s*industria/i.test(t);
  if (!ourSeen) return null;
  if (!biomeIsBuyer(t)) {
    // the seller's GSTIN is printed first; if that is ours, it is not a vendor paper
    if (gst.length && isOurGstin(gst[0].gstin)) return null;
  }
  const seller = gst.find((g) => !isOurGstin(g.gstin));
  let invNo =
    firstMatch(t, /Invoice\s*(?:No|Number)\s*\.?\s*:\s*([A-Z0-9][A-Z0-9\/\-]*)/i) ||
    firstMatch(t, /Invoice\s*#\s*:?\s*([A-Z0-9][A-Z0-9\/\-]*)/i) ||
    firstMatch(t, /Invoice\s*No\.?\s*(?:e-?Way\s*Bill\s*No\.?)?\s*\|?\s*([A-Z0-9][A-Z0-9\/\-]*\/[A-Z0-9\/\-]*|\d{1,6}\/20\d{2}-\d{2})/i) ||
    null;
  if (invNo && /^(dated|date|e-?way|transport)$/i.test(invNo)) invNo = null;
  if (!invNo) {
    // GRF style: the number sits apart from its label ("26/2026-27")
    invNo = firstMatch(t, /(?:^|\n|\|)\s*(\d{1,6}\/20\d{2}-\d{2})\s*(?:\n|\||$)/) || null;
  }
  if (!invNo && einvoiceDetail) invNo = firstMatch(t, /Document\s*Date\s*\|*\s*(\d{1,6})\b/i) || firstMatch(t, /(?:^|\n|\|)\s*(\d{1,6})\s+IGST\s+applicable/i);
  const date =
    firstDateAfter(t, /(?:Bill\s*)?Dated\s*:?/i, 30) ||
    firstDateAfter(t, /Invoice\s*Date\s*:?/i, 30) ||
    firstDateAfter(t, /Ack\.?\s*Date\s*:?/i, 30) ||
    allDates(t)[0] ||
    null;
  const flat12 = t.replace(/(\d{4})\s(\d{4})\s(\d{4})/g, "$1$2$3");
  const eway = firstMatch(flat12, /E-?\s?Way\s*Bill\s*No\.?\s*:?\s*\|?\s*(?:[A-Z0-9\/-]+\s+)?(\d{12})\b/i);
  const vehicle = (firstMatch(t, /Vehicle\s*No\.?\s*:?\s*\|?\s*(?:Freight\s*)?([A-Z]{2}\s?[0O]?\d{1,2}\s?[A-Z]{0,3}\s?\d{4})/i) || "").replace(/\s/g, "").toUpperCase().replace(/^([A-Z]{2})O/, "$10") || platesIn(t)[0] || null;
  const gr = firstMatch(t, /GR\s*\/?\s*RR\s*No\.?\s*:?\s*(\d{1,6})\b/i) || firstMatch(t, /G\.?\s?R\.?\s*No\.?\s*:?\s*(\d{1,6})\b/i);
  const transporter = firstMatch(t, /\bTransport\s*:\s*([A-Za-z][A-Za-z .&]{2,40}?)\s*(?:Dated|Vehicle|Station|\n|\||$)/i);
  const vendorName = signatureName(t) || null;
  const shipTo = firstLineAfter(t, /Ship(?:ped)?\s*to\s*:?\s*-?/i) || firstLineAfter(t, /Consignee\s*\(\s*Ship\s*to\s*\)/i) || firstLineAfter(t, /Shipping\s*Address\s*:?/i);
  return {
    layout: einvoiceDetail ? "vendor_einvoice_detail" : "vendor_tax_invoice",
    documentType: "vendor_tax_invoice",
    issuerSide: "them",
    confidence: invNo ? 96 : 88,
    vendorDocNo: invNo,
    vendorOwnDocNo: invNo,
    vendorDocCore: docCore(invNo),
    vendorGstin: seller ? seller.gstin : null,
    vendorName,
    documentDate: date,
    ewayBillNo: eway || null,
    vehicleNo: vehicle,
    grNumber: gr || null,
    quantityKg: quantityKg(t),
    transporterName: transporter || null,
    clientName: shipTo && !/biome/i.test(shipTo) ? chooseClient([shipTo], ctx, t, { matchedOnly: true }) : null,
  };
}

const KNOWN_TRANSPORTERS = /(kapil\s*roadways|delhi\s*barwala\s*road\s*lines|jai\s*shree\s*ram\s*transport|shiv\s*logistics|yash\s*traders|a\s*r\s*.?\s*trading\s*company|[A-Z][A-Za-z]+\s+(?:road\s?ways|road\s?lines|logistics|transport(?:\s*co\.?)?|carriers?|freight\s*carriers))/i;

function readBilty(text) {
  const t = String(text || "");
  if (/T\s?A\s?X\s*I\s?N\s?V\s?O\s?[IL]\s?C\s?E/i.test(head(t, 400)) || isEwayPage(t)) return null;
  const hits = countHits(t, BILTY_WORDS);
  const named = t.match(KNOWN_TRANSPORTERS);
  if (hits < 2 && !(hits >= 1 && named)) return null;
  const slipHits = countHits(t, SLIP_WORDS.slice(0, 12));
  if (slipHits >= 3 && hits < 3) return null;
  const no =
    firstMatch(t, /\bL\.?\s?R\.?\s*No\.?\s*[:.\/]?\s*(\d[\d ]{0,6}\d|\d)\b/i) ||
    firstMatch(t, /\b(?:G\.?\s?R|C\.?\s?N|Bilty)\s*No\.?\s*[:.\/]?\s*(\d{1,6})\b/i) ||
    firstMatch(t, /CONSIGNMENT\s*\|?\s*NOTE[\s\S]{0,400}?(?:^|\n|\|)\s*(\d{2,6})\s*(?:\n|\||$)/im) ||
    null;
  const gst = gstinsIn(t).find((g) => !isOurGstin(g.gstin));
  return {
    layout: "bill_t",
    documentType: "bilty_lr",
    issuerSide: "shared",
    confidence: hits >= 3 || named ? 93 : 86,
    grNumber: no ? no.replace(/\s/g, "") : null,
    transporterName: named ? named[1].replace(/\s+/g, " ").trim() : null,
    transporterGstin: gst ? gst.gstin : null,
    vehicleNo: platesIn(t)[0] || null,
    documentDate: allDates(t)[0] || null,
  };
}

function readWeightSlip(text) {
  const t = String(text || "");
  if (/T\s?A\s?X\s*I\s?N\s?V\s?O\s?[IL]\s?C\s?E/i.test(head(t, 300)) || isEwayPage(t) || isConsignmentTag(t)) return null;
  const hits = countHits(t, SLIP_WORDS);
  if (hits < 2) return null;
  const biltyHits = countHits(t, BILTY_WORDS);
  if (biltyHits >= 3 && hits < 4) return null;
  const num = (re) => {
    const v = firstMatch(t, re);
    if (!v) return null;
    const n = Number(String(v).replace(/[^\d]/g, ""));
    return n >= 1000 && n <= 90000 ? n : null;
  };
  let net = num(/Net{1,2}\s*(?:Wt|Weight)?\.?\s*[:=«]?\s*\|?\s*([\d,]{4,7})\s*(?:kg|Kg|KG|Ky)?/i);
  const gross = num(/Gross\s*(?:Wt|Weight)?\.?\s*[:=«]?\s*\|?\s*([\d,]{4,7})/i);
  const tare = num(/Tare\s*(?:Wt|Weight)?\.?\s*[:=«]?\s*\|?\s*([\d,]{4,7})/i);
  if (!net && gross && tare && gross > tare) net = gross - tare;
  const loaded = num(/Loaded[\s\S]{0,40}?([\d,]{4,7})/i);
  const empty = num(/Empty[\s\S]{0,40}?([\d,]{4,7})/i);
  if (!net && loaded && empty && loaded > empty) net = loaded - empty;
  const dates = allDates(t);
  return {
    layout: /biome\s*industria/i.test(t) ? "plant_weight_slip" : "weight_slip",
    documentType: "weight_slip",
    issuerSide: "shared",
    confidence: hits >= 3 ? 93 : 86,
    vehicleNo: platesIn(t)[0] || null,
    netWeight: net ? String(net) : null,
    quantityKg: net || null,
    grossWeight: gross ? String(gross) : loaded ? String(loaded) : null,
    tareWeight: tare ? String(tare) : empty ? String(empty) : null,
    documentDate: dates[0] || null,
    slipNo: firstMatch(t, /(?:RST\s*No|Serial\s*No|Slip\s*No|Weighment\s*Slip\s*No)\.?\s*[:.]?\s*(\d{2,8})/i),
    plantSlip: /biome\s*industria/i.test(t),
  };
}

/**
 * Read one page / one document's text.
 * @returns {null | object} layout name, documentType, issuerSide, confidence and fields
 */
function readLayout(text, ctx = {}) {
  const t = String(text || "");
  if (t.replace(/\s/g, "").length < 15) return null;
  return (
    readOurEwayOrVendorEway(t) ||
    readConsignmentTag(t, ctx) ||
    readOurInvoiceOrChallan(t, ctx) ||
    readVendorInvoice(t, ctx) ||
    readBilty(t) ||
    readWeightSlip(t) ||
    null
  );
}

