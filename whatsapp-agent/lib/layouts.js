/**
 * Biome Platform — WhatsApp Agent / real document layouts
 * -------------------------------------------------------------------
 * Precise rules for the documents the company actually exchanges,
 * learned from the owner's own set (Oct 2026):
 *
 *   OUR documents (seller = Biome, GSTIN 06AAJCB1927H1ZS)
 *     - Tally e-invoice "TAX INVOICE"  ........ Invoice No. BI-26-27-HR0841
 *     - Tally "DELIVERY NOTE"  ................. BIPL/2026-27/868
 *     - NTPC "DELIVERY CHALLAN" (Gangakhed)  ... Challan No. BI/NTPC/SOL/039
 *     - Tally e-way bill page  ................. Doc No. : Tax Invoice - BI-26-27-HR0841
 *     - Govt e-way bill print  ................. Generated By: 06AAJCB1927H1ZS
 *     - Consignment tag (Annexure-II)
 *   VENDOR documents (buyer / recipient = Biome)
 *     - tax invoices from many billing programs, e-invoice detail pages,
 *       e-way bills (Generated By = the vendor's GSTIN)
 *   SHARED physical papers
 *     - Bill T (bilty / lorry receipt / consignment note) — usually blank
 *     - weight slips (dharam kanta / weigh bridge), often Hindi or
 *       dot-matrix, sometimes printed with BIOME's name (our plant's bridge)
 *
 * A layout is only reported when its tell-tale features are present; the
 * caller keeps its own reading otherwise. Every value returned here comes
 * from a labelled field or a number format only that document uses.
 */

const OUR_GSTIN = "06AAJCB1927H1ZS";
const OUR_PAN = "AAJCB1927H";

