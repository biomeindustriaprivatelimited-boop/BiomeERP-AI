function head(text, n = 400) {
  return String(text || "").slice(0, n);
}

function isEwayPage(text) {
  const t = String(text || "");
  const top = head(t, 260);
  if (!/e\s?-?\s?way\s?bil/i.test(top)) return false;
  return /generated\s*(by|date)|gstin\s*of\s*supplier|e-?way\s*bill\s*details|part\s*-?\s*[ab]\b|e-?way\s*bil+\s*date/i.test(t);
}

function isConsignmentTag(text) {
  return /tag\s+for\s+consignment/i.test(text) || (/annexure\s*-?\s*ii/i.test(text) && /consignment/i.test(text));
}

