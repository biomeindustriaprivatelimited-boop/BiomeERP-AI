const OUR_NO_RES = [
  /\bBI-?\s?\d{2}-?\s?\d{2}-?\s?[A-Z]{2}\s?\d{3,5}\b/, // BI-26-27-HR0841 (tax invoice)
  /\bBIPL\s?\/\s?\d{4}-\d{2}\s?\/\s?\d{1,5}\b/, // BIPL/2026-27/868 (delivery note)
  /\bBI\s?\/\s?[A-Z]{2,8}\s?\/\s?[A-Z]{2,8}\s?\/\s?\d{1,5}\b/, // BI/NTPC/SOL/039 (NTPC challan)
];
function ourDocNumber(text) {
  const t = String(text || "").toUpperCase();
  for (const re of OUR_NO_RES) {
    const m = t.match(re);
    if (m) return m[0].replace(/\s+/g, "");
  }
  return null;
}

/** "BDC/841/AA/37", "BDC854/CE/285", "BDC39/GKD/39" → canonical text. */
function referenceIn(text) {
  const t = String(text || "").toUpperCase();
  const m = t.match(/\bBDC\s*\/?\s*(\d{1,5})\s*[\/\\|]\s*([A-Z]{1,6})\s*[\/\\|]\s*([A-Z0-9][A-Z0-9-]{0,11})\b/);
  if (!m) return null;
  return `BDC/${m[1]}/${m[2]}/${m[3]}`;
}

function firstMatch(text, re, group = 1) {
  const m = String(text || "").match(re);
  return m ? String(m[group]).trim() : null;
}

/** The name a seller signs with: "For ANCHAL TRADERS", "for Soami Agro Industries". */
function signatureName(text) {
  const re = /\bfor\s+([A-Z][A-Za-z.&'\- ]{2,60}?)(?:,|\n|\||\s{2,}|\s+Authori[sz]ed|\s+Auth\.|\s+Digitally|$)/gim;
  let m;
  let last = null;
  while ((m = re.exec(String(text || "")))) {
    const name = m[1].trim();
    if (/biome/i.test(name)) continue;
    if (/^(the|doing|use|any|payment|purpose|buyer|transporter|office|extra|recipient|your|us)\b/i.test(name)) continue;
    if (name.split(/\s+/).length > 7) continue;
    last = name;
  }
  return last;
}

