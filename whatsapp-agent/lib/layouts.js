/** OCR spells our GSTIN "O6AAJ CB192 7H1ZS", "06AAJCB1927H1Zs"… */
function normGstin(raw) {
  let s = String(raw || "").toUpperCase().replace(/[^A-Z0-9]/g, "");
  if (s.length !== 15) return null;
  // first two are digits (state code), then PAN (5 letters, 4 digits, 1 letter)
  const dig = (x) => x.replace(/O/g, "0").replace(/[IL]/g, "1").replace(/S/g, "5").replace(/Z/g, "2").replace(/B/g, "8");
  s = dig(s.slice(0, 2)) + s.slice(2, 7) + dig(s.slice(7, 11)) + s.slice(11);
  if (!/^\d{2}[A-Z]{5}\d{4}[A-Z][0-9A-Z]{3}$/.test(s)) return null;
  return s;
}

function isOurGstin(g) {
  const s = normGstin(g);
  if (!s) return false;
  return s === OUR_GSTIN || s.slice(2, 12) === OUR_PAN;
}

/** Every GSTIN on the page, in order, tolerant of the spaced e-way style. */
function gstinsIn(text) {
  const out = [];
  // e-way bills space GSTINs out ("06AAJ CB192 7H1ZS"): join single spaces between alphanumerics first
  const t = String(text || "").toUpperCase().replace(/([A-Z0-9]) (?=[A-Z0-9])/g, "$1");
  const re = /(?<![A-Z0-9])([0-9OS]{2}[A-Z]{5}[0-9OILSZB]{4}[A-Z][0-9A-Z]{2}[0-9A-Z])/g;
  let m;
  while ((m = re.exec(t))) {
    const g = normGstin(m[1]);
    if (g && !out.some((x) => x.gstin === g)) out.push({ gstin: g, at: m.index });
  }
  return out;
}

const PLATE_RE = /\b([A-Z]{2})\s?-?(\d{1,2})\s?-?([A-Z]{0,3})\s?-?(\d{4})\b/g;
/** Vehicle numbers on the page, in order (HR63E2262, PB07BT5796, MH26AD1886). */
function platesIn(text) {
  const out = [];
  const t = String(text || "").toUpperCase().replace(/\bPBO(\d)/g, "PB0$1");
  let m;
  PLATE_RE.lastIndex = 0;
  while ((m = PLATE_RE.exec(t))) {
    const st = m[1];
    if (!STATE_CODES.has(st)) continue;
    const p = `${st}${m[2].padStart(2, "0")}${m[3]}${m[4]}`;
    if (!out.includes(p)) out.push(p);
  }
  return out;
}
const STATE_CODES = new Set("AN AP AR AS BR CG CH DD DL DN GA GJ HP HR JH JK KA KL LA LD MH ML MN MP MZ NL OD OR PB PY RJ SK TN TR TS UK UP WB".split(" "));

const MONTHS = { jan: 1, feb: 2, mar: 3, apr: 4, may: 5, jun: 6, jul: 7, aug: 8, sep: 9, oct: 10, nov: 11, dec: 12 };
/** "1-Aug-26", "01-08-2026", "26/07/2026", "25 Jul 2026", "2026-07-30" → ISO. */
function parseDateToken(s) {
  const t = String(s || "").trim();
  let m = t.match(/^(\d{1,2})[-\s.\/]([A-Za-z]{3})[A-Za-z]*[-\s.\/,]+(\d{2,4})$/);
  if (m) {
    const mo = MONTHS[m[2].toLowerCase()];
    if (!mo) return null;
    const y = m[3].length === 2 ? 2000 + Number(m[3]) : Number(m[3]);
    return iso(y, mo, Number(m[1]));
  }
  m = t.match(/^(\d{1,2})[-.\/](\d{1,2})[-.\/](\d{2,4})$/);
  if (m) {
    const y = m[3].length === 2 ? 2000 + Number(m[3]) : Number(m[3]);
    return iso(y, Number(m[2]), Number(m[1]));
  }
  m = t.match(/^(20\d{2})-(\d{1,2})-(\d{1,2})$/);
  if (m) return iso(Number(m[1]), Number(m[2]), Number(m[3]));
  return null;
}
function iso(y, mo, d) {
  if (!(y >= 2020 && y <= 2040 && mo >= 1 && mo <= 12 && d >= 1 && d <= 31)) return null;
  return `${y}-${String(mo).padStart(2, "0")}-${String(d).padStart(2, "0")}`;
}
const DATE_TOKEN = "(\\d{1,2}[-.\\/ ](?:[A-Za-z]{3}[A-Za-z]*|\\d{1,2})[-.\\/ ,]+\\d{2,4}|20\\d{2}-\\d{1,2}-\\d{1,2})";
function firstDateAfter(text, labelRe, within = 60) {
  const src = String(text || "");
  const re = new RegExp(labelRe.source, labelRe.flags.includes("g") ? labelRe.flags : labelRe.flags + "g");
  let m;
  while ((m = re.exec(src))) {
    const tail = src.slice(m.index + m[0].length, m.index + m[0].length + within);
    const d = tail.match(new RegExp(DATE_TOKEN));
    if (d) {
      const v = parseDateToken(d[1]);
      if (v) return v;
    }
  }
  return null;
}
function allDates(text) {
  const out = [];
  const re = new RegExp(DATE_TOKEN, "g");
  let m;
  while ((m = re.exec(String(text || "")))) {
    const v = parseDateToken(m[1]);
    if (v) out.push(v);
  }
  return out;
}

/** Quantity in kg from "35,770 KG", "33.995 Ton", "423.30 QTL", "17.130 MTS". */
function toKg(num, unit) {
  const n = Number(String(num).replace(/,/g, ""));
  if (!Number.isFinite(n) || n <= 0) return null;
  const u = String(unit || "").toUpperCase();
  if (/^(KG|KGS|KILO)/.test(u)) return Math.round(n);
  if (/^(MT|MTS|TON|TONNE|TONNES|TONS)/.test(u)) return Math.round(n * 1000);
  if (/^(QTL|QUINTAL)/.test(u)) return Math.round(n * 100);
  return null;
}
function quantityKg(text) {
  const lines = String(text || "").split(/\n/);
  for (const line of lines) {
    if (!/\b(Grand\s*)?Total\b/i.test(line) || /Total\s*(Tax|Inv|Items|amount\s*\(in)/i.test(line)) continue;
    const q = quantityKgRaw(line);
    if (q) return q;
  }
  return quantityKgRaw(text);
}
function quantityKgRaw(text) {
  const re = /(\d{1,3}(?:,\d{2,3})+(?:\.\d+)?|\d+(?:\.\d+)?)\s*(KGS?\b|Kgs\.?|KG\b|MTS?\b|Tonnes?\b|TONS?\b|Ton\b|QTL\b|Qtl\b)/gi;
  let m;
  const found = [];
  while ((m = re.exec(String(text || "")))) {
    const kg = toKg(m[1], m[2].replace(/\./g, ""));
    if (kg && kg >= 1000 && kg <= 80000) found.push(kg);
  }
  return found.length ? found[0] : null;
}

/** 12-digit e-way bill number, also written "3422 8582 7120". */
function ewayNumbers(text) {
  const out = [];
  const re = /(?<![\d])(\d{4}\s?\d{4}\s?\d{4})(?![\d])/g;
  let m;
  while ((m = re.exec(String(text || "")))) {
    const n = m[1].replace(/\s/g, "");
    if (/^[1-9]\d{11}$/.test(n) && !out.includes(n)) out.push(n);
  }
  return out;
}

/** The numeric core of a document number: BI-26-27-HR0841 → 841, 37/2026-27 → 37. */
function docCore(no) {
  const s = String(no || "").toUpperCase();
  // "37/2026-27": number first, financial year after
  let m = s.match(/^(\d{1,6})\s*\/\s*20\d{2}-?\d{2}$/);
  if (m) return String(Number(m[1]));
  m = s.match(/(\d+)\s*$/);
  return m ? String(Number(m[1])) : null;
}

